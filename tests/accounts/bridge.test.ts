import { afterEach, expect, test, vi } from "vitest";
import WebSocket, { WebSocketServer } from "ws";
import { CodexTuiBridge } from "../../src/adapters/codex/tui-bridge.js";
import { AccountSwitchGate } from "../../src/accounts/switch-gate.js";
const cleanup: (() => unknown)[] = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); });

test("TUI review admission is held through its response and auth refresh stays behind the bridge", async () => {
  const server = new WebSocketServer({ host: "127.0.0.1", port: 0 }); cleanup.push(() => server.close());
  await new Promise(resolve => server.once("listening", resolve));
  const address = server.address(); if (!address || typeof address === "string") throw Error();
  let upstream!: WebSocket;
  const messages: any[] = [];
  server.on("connection", socket => { upstream = socket; cleanup.push(() => socket.terminate()); socket.on("message", raw => messages.push(JSON.parse(raw.toString()))); });
  const gate = new AccountSwitchGate({ pollMs: 1, request: async () => ({ data: [], nextCursor: null }) });
  const refresh = vi.fn(async () => ({ accessToken: "private-only" }));
  const bridge = new CodexTuiBridge({ endpoint: `ws://127.0.0.1:${address.port}`, decorateThreadStart: p => p, claimThread() {}, openThreadClient() {}, closeThreadClient() {}, ownsThread: () => true, dispatchTool: async () => null, observeNotification() {}, admitModelRequest: (method, admission) => gate.enter(method, admission), refreshAccount: refresh });
  const url = await bridge.start(); cleanup.push(() => bridge.close());
  const tui = new WebSocket(url); cleanup.push(() => tui.terminate());
  const received: any[] = []; tui.on("message", raw => received.push(JSON.parse(raw.toString())));
  await new Promise(resolve => tui.once("open", resolve));
  tui.send(JSON.stringify({ id: 1, method: "review/start", params: { threadId: "original" } }));
  await vi.waitFor(() => expect(messages.some(m => m.id === 1)).toBe(true));
  let ready = false; const prepared = gate.prepare("switch").then(() => { ready = true; });
  tui.send(JSON.stringify({ id: 2, method: "review/start", params: { threadId: "original" } }));
  await vi.waitFor(() => expect(received.some(m => m.id === 2 && m.error)).toBe(true));
  expect(ready).toBe(false); expect(messages.some(m => m.id === 2)).toBe(false);
  upstream.send(JSON.stringify({ id: 1, result: { turn: { id: "t" } } })); await prepared;
  upstream.send(JSON.stringify({ id: 90, method: "account/chatgptAuthTokens/refresh", params: { reason: "unauthorized", previousAccountId: "b" } }));
  await vi.waitFor(() => expect(messages.some(m => m.id === 90 && m.result?.accessToken === "private-only")).toBe(true));
  expect(received.some(m => m.id === 90)).toBe(false);
  gate.release("switch");
  let permit!: string, sendAdmitted!: () => void;
  const admitted = gate.withAdmission("turn/start", async admission => {
    permit = admission.token;
    await new Promise<void>(resolve => { sendAdmitted = resolve; });
    tui.send(JSON.stringify({ id: 10, method: "turn/start", params: { threadId: "original" }, accountAdmissionToken: admission.token }));
    await vi.waitFor(() => expect(received.some(m => m.id === 10 && m.result)).toBe(true));
  });
  const drain = gate.prepare("next-switch"); sendAdmitted();
  await vi.waitFor(() => expect(messages.some(m => m.id === 10)).toBe(true));
  expect(messages.find(m => m.id === 10)).not.toHaveProperty("accountAdmissionToken");
  expect(gate.isPrepared("next-switch")).toBe(false);
  upstream.send(JSON.stringify({ id: 10, result: { turn: { id: "accepted" } } }));
  await admitted; await drain;
  tui.send(JSON.stringify({ id: 11, method: "turn/start", params: {}, accountAdmissionToken: permit }));
  await vi.waitFor(() => expect(received.some(m => m.id === 11 && m.error)).toBe(true));
  expect(messages.some(m => m.id === 11)).toBe(false);
  gate.release("next-switch");
  tui.send(JSON.stringify({ id: 12, method: "turn/start", params: {} }));
  await vi.waitFor(() => expect(messages.some(m => m.id === 12)).toBe(true));
  upstream.send(JSON.stringify({ id: 12 }));
  await vi.waitFor(() => expect(received.some(m => m.id === 12)).toBe(true));
  await gate.prepare("malformed-response");
  expect(gate.isPrepared("malformed-response")).toBe(true);
  gate.release("malformed-response");
});

test("a TUI dropping with in-flight model work does not fence later sessions", async () => {
  const server = new WebSocketServer({ host: "127.0.0.1", port: 0 }); cleanup.push(() => server.close());
  await new Promise(resolve => server.once("listening", resolve));
  const address = server.address(); if (!address || typeof address === "string") throw Error();
  const sockets: WebSocket[] = [];
  const messages: any[] = [];
  server.on("connection", socket => { sockets.push(socket); cleanup.push(() => socket.terminate()); socket.on("message", raw => messages.push(JSON.parse(raw.toString()))); });
  const gate = new AccountSwitchGate({ pollMs: 1, request: async () => ({ data: [], nextCursor: null }) });
  const bridge = new CodexTuiBridge({ endpoint: `ws://127.0.0.1:${address.port}`, decorateThreadStart: p => p, claimThread() {}, openThreadClient() {}, closeThreadClient() {}, ownsThread: () => true, dispatchTool: async () => null, observeNotification() {}, admitModelRequest: (method, admission) => gate.enter(method, admission) });
  const url = await bridge.start(); cleanup.push(() => bridge.close());
  const first = new WebSocket(url);
  await new Promise(resolve => first.once("open", resolve));
  first.send(JSON.stringify({ id: 1, method: "turn/start", params: { threadId: "original" } }));
  await vi.waitFor(() => expect(messages.some(m => m.id === 1)).toBe(true));
  first.terminate();
  await new Promise(resolve => first.once("close", resolve));
  const second = new WebSocket(url); cleanup.push(() => second.terminate());
  const received: any[] = []; second.on("message", raw => received.push(JSON.parse(raw.toString())));
  await new Promise(resolve => second.once("open", resolve));
  second.send(JSON.stringify({ id: 2, method: "turn/start", params: { threadId: "original" } }));
  await vi.waitFor(() => expect(messages.some(m => m.id === 2)).toBe(true));
  expect(received.some(m => m.id === 2 && m.error)).toBe(false);
  sockets[sockets.length - 1].send(JSON.stringify({ id: 2, result: { turn: { id: "recovered" } } }));
  await vi.waitFor(() => expect(received.some(m => m.id === 2 && m.result)).toBe(true));
  await gate.prepare("switch-after-drop");
  expect(gate.isPrepared("switch-after-drop")).toBe(true);
  gate.release("switch-after-drop");
});
